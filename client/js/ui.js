// ───────── DOM ─────────
export const $ = (selector, root = document) => root.querySelector(selector);
export const $$ = (selector, root = document) => [...root.querySelectorAll(selector)];

export function escapeHtml(value) {
  return String(value ?? '')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#39;');
}

// Tagged template tự escape biến: html`<p>${userText}</p>`; dùng raw() cho HTML tin cậy
const RAW = Symbol('raw');
export const raw = (value) => ({ [RAW]: true, value: String(value ?? '') });
export function html(strings, ...values) {
  return strings.reduce((out, str, i) => {
    if (i >= values.length) return out + str;
    const v = values[i];
    const rendered = Array.isArray(v)
      ? v.map((x) => (x?.[RAW] ? x.value : escapeHtml(x))).join('')
      : v?.[RAW]
        ? v.value
        : v === false || v == null
          ? ''
          : escapeHtml(v);
    return out + str + rendered;
  }, '');
}

export const debounce = (fn, wait = 300) => {
  let timer;
  return (...args) => {
    clearTimeout(timer);
    timer = setTimeout(() => fn(...args), wait);
  };
};

