// Chuỗi cho <input type="datetime-local"> theo giờ địa phương
export function toDateTimeLocal(value) {
  if (!value) return '';
  const d = new Date(value);
  const pad = (n) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}`;
}

export const toDateInput = (value) => (value ? toDateTimeLocal(value).slice(0, 10) : '');

// ───────── Toast ─────────
export function toast(message, type = 'info', duration = 3600) {
  let stack = $('.toast-stack');
  if (!stack) {
    stack = document.createElement('div');
    stack.className = 'toast-stack';
    stack.setAttribute('role', 'status');
    stack.setAttribute('aria-live', 'polite');
    document.body.append(stack);
  }
  const iconName = { success: 'check-circle', error: 'alert-circle', info: 'info' }[type] ?? 'info';
  const el = document.createElement('div');
  el.className = `toast toast-${type}`;
  el.innerHTML = `${icon(iconName, 18)}<span>${escapeHtml(message)}</span>`;
  stack.append(el);
  setTimeout(() => {
    el.classList.add('leaving');
    setTimeout(() => el.remove(), 220);
  }, duration);
}

// ───────── Form ─────────
export function setLoading(button, loading) {
  if (!button) return;
  if (loading) {
    button.dataset.label = button.innerHTML;
    button.setAttribute('aria-busy', 'true');
    button.innerHTML = `<span class="spinner"></span>${button.dataset.loadingText ?? 'Đang xử lý...'}`;
  } else {
    button.removeAttribute('aria-busy');
    if (button.dataset.label) button.innerHTML = button.dataset.label;
  }
}

export function clearFieldErrors(form) {
  $$('.field-error[data-generated]', form).forEach((el) => el.remove());
  $$('[aria-invalid="true"]', form).forEach((el) => el.removeAttribute('aria-invalid'));
}

// details: [{ field, message }] từ API → hiện ngay dưới input tương ứng
export function showFieldErrors(form, details = []) {
  clearFieldErrors(form);
  let firstInvalid = null;
  const shown = new Set();
  for (const { field, message } of details) {
    const name = field?.split('.')[0];
    if (!name || shown.has(name)) continue;
    const input = form.elements.namedItem(name);
    const target = input instanceof RadioNodeList ? input[0] : input;
    if (!target) continue;
    shown.add(name);
    target.setAttribute?.('aria-invalid', 'true');
    const error = document.createElement('p');
    error.className = 'field-error';
    error.dataset.generated = '';
    error.textContent = message;
    (target.closest('.field') ?? target.parentElement).append(error);
    firstInvalid ??= target;
  }
  firstInvalid?.focus?.();
  return shown.size;
}

export function handleFormError(form, error, fallback = 'Đã có lỗi xảy ra') {
  const shown = form && error?.details?.length ? showFieldErrors(form, error.details) : 0;
  if (!shown) toast(error?.message ?? fallback, 'error');
}

export function togglePasswordButtons(root = document) {
  $$('[data-toggle-password]', root).forEach((btn) => {
    btn.innerHTML = icon('eye', 18);
    btn.addEventListener('click', () => {
      const input = btn.parentElement.querySelector('input');
      const show = input.type === 'password';
      input.type = show ? 'text' : 'password';
      btn.innerHTML = icon(show ? 'eye-off' : 'eye', 18);
      btn.setAttribute('aria-label', show ? 'Ẩn mật khẩu' : 'Hiện mật khẩu');
    });
  });
}

// ───────── Dialog xác nhận ─────────
export function confirmDialog({ title = 'Xác nhận', message, confirmText = 'Xác nhận', danger = false }) {
  return new Promise((resolve) => {
    const dialog = document.createElement('dialog');
    dialog.className = 'dialog';
    dialog.innerHTML = html`
      <div class="dialog-head"><h2 class="dialog-title">${title}</h2></div>
      <div class="dialog-body"><p>${message}</p></div>
      <div class="dialog-foot">
        <button type="button" class="btn btn-ghost btn-sm" data-action="cancel">Hủy</button>
        <button type="button" class="btn ${danger ? 'btn-danger' : 'btn-dark'} btn-sm" data-action="ok">${confirmText}</button>
      </div>`;
    document.body.append(dialog);
    const close = (result) => {
      dialog.close();
      dialog.remove();
      resolve(result);
    };
    dialog.addEventListener('click', (e) => {
      const action = e.target.closest('[data-action]')?.dataset.action;
      if (action) close(action === 'ok');
      else if (e.target === dialog) close(false);
    });
    dialog.addEventListener('cancel', (e) => {
      e.preventDefault();
      close(false);
    });
    dialog.showModal();
    $('[data-action="ok"]', dialog).focus();
  });
}

// ───────── Phân trang ─────────
export function renderPagination(container, meta, onChange) {
  if (!meta || meta.total === 0) {
    container.innerHTML = '';
    return;
  }
  const { page, totalPages, total, limit } = meta;
  const from = (page - 1) * limit + 1;
  const to = Math.min(page * limit, total);
  const pages = [];
  for (let p = 1; p <= totalPages; p += 1) {
    if (p === 1 || p === totalPages || Math.abs(p - page) <= 1) pages.push(p);
    else if (pages.at(-1) !== '…') pages.push('…');
  }
  container.innerHTML = html`
    <span>Hiển thị ${from}–${to} / ${total}</span>
    <div class="pagination-pages">
      <button class="page-btn" data-page="${page - 1}" ${page <= 1 ? raw('disabled') : ''} aria-label="Trang trước">${raw(icon('chevron-left', 16))}</button>
      ${pages.map((p) =>
        p === '…'
          ? raw('<span class="page-btn" aria-hidden="true" style="border:0">…</span>')
          : raw(`<button class="page-btn" data-page="${p}" ${p === page ? 'aria-current="page"' : ''}>${p}</button>`),
      )}
      <button class="page-btn" data-page="${page + 1}" ${page >= totalPages ? raw('disabled') : ''} aria-label="Trang sau">${raw(icon('chevron-right', 16))}</button>
    </div>`;
  container.onclick = (e) => {
    const btn = e.target.closest('[data-page]');
    if (btn && !btn.disabled && Number(btn.dataset.page) !== page) onChange(Number(btn.dataset.page));
  };
}

